package main

import (
	"log"
	"os"
)

func BasicLoggingExamples() {
	// Логирование с автоматическим переносом строки
	log.Print("Сообщение без автоматического перевода строки")
	log.Print(" - продолжение на той же строке\n")

	// Простое логирование сообщения
	log.Println("Это простое сообщение лога")

	// Логирование с форматированием
	name := "John"
	age := 30
	log.Printf("Пользователь: %s, возраст: %d", name, age)

	// Фатальное логирование (завершает программу)
	// log.Fatal("Критическая ошибка - программа завершается")
	log.Println("Fatal закомментирован, чтобы не завершить программу")

	// Panic логирование (вызывает панику)
	// log.Panic("Паника в программе")
	log.Println("Panic закомментирован, чтобы не вызвать панику")
}

// LogLevelsSimulation показывает имитацию уровней логирования
func LogLevelsSimulation() {
	log.Println("\n=== Имитация уровней логирования ===")

	// INFO уровень
	log.Printf("[INFO] Информационное сообщение: операция выполнена успешно")

	// WARNING уровень
	log.Printf("[WARNING] Предупреждение: устаревший метод используется")

	// ERROR уровень
	log.Printf("[ERROR] Ошибка: не удалось подключиться к базе данных")
}

func ErrorLogging() {
	log.Println("\n=== Логирование ошибок ===")

	// Создание ошибки
	_, err := os.Open("несуществующий_файл.txt")
	if err != nil {
		// Логирование ошибки
		log.Printf("Ошибка при открытии файла: %v", err)

		// Логирование с контекстом
		log.Printf("Не удалось прочитать конфигурацию из файла: %v", err)

		// Более подробное логирование
		log.Printf("ОШИБКА [%T]: %v", err, err)
	}
}

func main() {
	BasicLoggingExamples()
	LogLevelsSimulation()
	ErrorLogging()

	log.Println("\n=== Основные методы ===")
	log.Println("• log.Println() - простое логирование с переносом строки")
	log.Println("• log.Printf() - логирование с форматированием")
	log.Println("• log.Print() - логирование без автоматического перевода строки")
	log.Println("• log.Fatal() - критическая ошибка (завершает программу)")
	log.Println("• log.Panic() - паника (вызывает panic)")
}
